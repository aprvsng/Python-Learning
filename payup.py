print()
event = input("Enter the event name: ")
cost = float(input(f"Enter the cost of the {event}: "))
service_charge = float(input(f"Enter the service charge for the {event}: ").strip('%'))
total_service_charge = cost * (service_charge / 100)
group_size = int(input("Enter the number of people in the group: "))
grand_total = cost + service_charge
total_per_person = grand_total / group_size
print()
print("-" * 40)
print(f"Here is your bill for the event: {event}")
print()
print(f"Cost: ${cost:.2f}")
print(f"Service Charge: ${total_service_charge:.2f}")
print(f"Grand Total: ${grand_total:.2f}")
print(f"Total per person: ${total_per_person:.2f}")
print()
print("Thank you for using PayUp!")
